import { neon, NeonQueryFunction } from "@neondatabase/serverless";

export interface DbUser {
  id: number | string;
  username: string;
  password_hash: string;
  owner_name: string;
  created_at?: string;
}

/**
 * Resolves the Postgres connection URL from environment variables.
 * Checks standard names and any custom prefix configured in Vercel.
 */
export function getDatabaseUrl(): string | null {
  // 1. Direct standard names
  if (process.env.POSTGRES_URL) return process.env.POSTGRES_URL;
  if (process.env.DATABASE_URL) return process.env.DATABASE_URL;
  if (process.env.POSTGRES_PRISMA_URL) return process.env.POSTGRES_PRISMA_URL;
  if (process.env.POSTGRES_URL_NON_POOLING) return process.env.POSTGRES_URL_NON_POOLING;
  if (process.env.DATABASE_URL_UNPOOLED) return process.env.DATABASE_URL_UNPOOLED;

  // 2. Custom prefix generated by Vercel integrations (e.g. MEAL_BUILDER_POSTGRES_URL)
  for (const [key, value] of Object.entries(process.env)) {
    if (!value) continue;
    if (key.endsWith("_POSTGRES_URL") || key.endsWith("_DATABASE_URL")) {
      return value;
    }
  }

  // 3. Fallback: Any env var starting with postgres:// or postgresql://
  for (const [key, value] of Object.entries(process.env)) {
    if (!value) continue;
    if (value.startsWith("postgres://") || value.startsWith("postgresql://")) {
      return value;
    }
  }

  return null;
}

export function getSql(): NeonQueryFunction<false, false> | null {
  const url = getDatabaseUrl();
  if (!url) return null;
  return neon(url);
}

/**
 * Initializes the users table in Postgres if not already present.
 */
export async function initUsersTable(): Promise<void> {
  const sql = getSql();
  if (!sql) {
    throw new Error("Cannot initialize users table: database connection URL not found in environment.");
  }

  await sql`
    CREATE TABLE IF NOT EXISTS users (
      id SERIAL PRIMARY KEY,
      username TEXT UNIQUE NOT NULL,
      password_hash TEXT NOT NULL,
      owner_name TEXT NOT NULL,
      created_at TIMESTAMPTZ DEFAULT NOW()
    );
  `;
}

/**
 * Finds a user by username (case-insensitive).
 */
export async function findUserByUsername(username: string): Promise<DbUser | null> {
  const sql = getSql();
  if (!sql) {
    console.warn("Postgres database URL not configured. Returning null for user search.");
    return null;
  }

  const rows = await sql`
    SELECT id, username, password_hash, owner_name, created_at
    FROM users
    WHERE LOWER(username) = LOWER(${username.trim()})
    LIMIT 1;
  `;

  if (rows.length === 0) {
    return null;
  }

  const row = rows[0];
  return {
    id: row.id,
    username: row.username,
    password_hash: row.password_hash,
    owner_name: row.owner_name,
    created_at: row.created_at,
  };
}

/**
 * Inserts a new user into the database.
 */
export async function createUser(
  username: string,
  passwordHash: string,
  ownerName: string
): Promise<DbUser> {
  const sql = getSql();
  if (!sql) {
    throw new Error("Cannot create user: database connection URL not found.");
  }

  const rows = await sql`
    INSERT INTO users (username, password_hash, owner_name)
    VALUES (${username.trim()}, ${passwordHash}, ${ownerName.trim()})
    ON CONFLICT (username) DO UPDATE
    SET password_hash = EXCLUDED.password_hash,
        owner_name = EXCLUDED.owner_name
    RETURNING id, username, password_hash, owner_name, created_at;
  `;

  const row = rows[0];
  return {
    id: row.id,
    username: row.username,
    password_hash: row.password_hash,
    owner_name: row.owner_name,
    created_at: row.created_at,
  };
}
